#!/usr/bin/env python3
"""Write the W1 schematic (KiCad 7 file format; KiCad 7-10 open it) from design.py.

Reuses the schematic writer of M1 (hardware/m1-screen-knobs/gen/make_sch.py): every pin gets a
net label or a power symbol at its end, so the netlist matches design.py exactly.
Run: python3 make_sch.py
License: AGPL-3.0-or-later (code), CERN-OHL-S-2.0 (the generated schematic).
"""
import os
import sys
import uuid

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "m1-screen-knobs", "gen"))
import make_sch as M  # noqa: E402  (M1's writer; it imports M1's design as M.D, replaced below)

sys.path.insert(0, HERE)
sys.modules.pop("design", None)
import design as D  # noqa: E402

M.D = D
M.PROJ_LIB = os.path.join(D.M1_LIB, "ShtukaDruka.kicad_sym")
M.NS = uuid.UUID("1b6e7f0e-3c55-4d0e-9a3f-7a2f5c0d9e21")
M.ROOT = str(uuid.uuid5(M.NS, "root"))
OUT = os.path.join(HERE, "..", D.NAME + ".kicad_sch")


class Sch(M.Sch):
    def write(self, path):
        libs = "".join("  " + M.lib_block(l)[0].replace("\n", "\n  ") + "\n" for l in self.used)
        s = (f'(kicad_sch (version 20230121) (generator eeschema)\n\n  (uuid {M.ROOT})\n\n  (paper "A3")\n\n'
             f'  (title_block\n    (title {M.q(D.TITLE)})\n    (rev {M.q(D.REV)})\n'
             f'    (company "Shtuka Druka - open hardware, CERN-OHL-S-2.0")\n'
             f'    (comment 1 "Generated by hardware/w1-levels/gen/make_sch.py from design.py - edit the script, not this file")\n'
             f'    (comment 2 "I2C: ADS1115 0x48, IS31FL3218 0x54; chain: host reads P48 1, P48 2, six 1s, then M5")\n  )\n\n'
             f'  (lib_symbols\n{libs}  )\n\n' + "".join(self.items) +
             f'\n  (sheet_instances\n    (path "/" (page "1"))\n  )\n)\n')
        open(path, "w").write(s)


def main():
    P = {p["ref"]: p for p in D.parts()}
    S = Sch()

    def put(ref, x, y, r=0):
        p = P[ref]
        f = {k: v for k, v in p["fields"].items() if k not in ("DNP", "Side")}
        S.symbol(ref, p["lib"], p["value"], x, y, r, p["fp"], f, p["pins"])

    g = 2.54
    S.text("Module bus (R123): J1 to P1 over the fold, J2 to the M5 Gain module (passed through)", 10 * g, 8 * g)
    put("J1", 20 * g, 18 * g)
    put("J2", 50 * g, 18 * g)
    for net, x in (("+5V", 12), ("+3V3", 16), ("GND", 20)):
        S.power(net, x * g, 34 * g, 90 if net != "GND" else 270, flag=True)
    put("C1", 28 * g, 34 * g)
    put("C2", 34 * g, 34 * g)
    S.text("Volume pots Main, Cue Mix, Phones 1, Phones 2 -> ADS1115 (I2C 0x48)", 10 * g, 46 * g)
    for n in range(4):
        put(f"RV{n + 1}", (14 + 12 * n) * g, 56 * g)
        put(f"R{1 + n}", (18 + 12 * n) * g, 64 * g, 90)
        put(f"C{3 + n}", (22 + 12 * n) * g, 70 * g)
    put("U1", 74 * g, 62 * g)
    put("C7", 86 * g, 70 * g)
    S.text("P48 buttons -> 74HC165 in the module chain (between P1 and M5)", 70 * g, 8 * g)
    put("SW1", 74 * g, 18 * g, 90)
    put("SW2", 80 * g, 18 * g, 90)
    put("RN1", 88 * g, 18 * g)
    put("U2", 104 * g, 24 * g)
    put("C8", 116 * g, 34 * g)
    S.text("Button lights: IS31FL3218 (I2C 0x54), 2 RGB per button", 100 * g, 46 * g)
    put("U3", 112 * g, 62 * g)
    for i, ref in enumerate(("R5", "R6", "C9", "C10")):
        put(ref, (124 + 5 * i) * g, 52 * g)
    for n in range(4):
        put(f"D{n + 1}", (124 + 9 * n) * g, 70 * g)
    for h in range(6):
        put(f"H{h + 1}", (124 + 5 * h) * g, 84 * g)
    S.write(OUT)
    print("ok", OUT, len(P), "parts")


if __name__ == "__main__":
    main()
