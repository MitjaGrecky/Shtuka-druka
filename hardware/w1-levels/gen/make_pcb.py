#!/usr/bin/env python3
"""Build the W1 board from design.py with KiCad's pcbnew Python module (KiCad 7 or newer),
optionally autoroute it with Freerouting 1.9.

  python3 make_pcb.py                                    # placement + nets, unrouted
  python3 make_pcb.py --route freerouting-1.9.0.jar      # + autorouting (xvfb-run, Java)
  python3 make_pcb.py --ses gen/last_route.ses           # rebuild from the last routing

Stack-up: 2 layers (JLCPCB standard). Top: pots, P48 switches and their LEDs. Bottom: ICs,
passives, both bus connectors. GND pours on both sides after routing, stitched with vias.
The routing, session import, project rules and stitching come from M1's make_pcb.py.
License: AGPL-3.0-or-later (code), CERN-OHL-S-2.0 (the generated board).
"""
import os
import sys

import pcbnew

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "m1-screen-knobs", "gen"))
import make_pcb as M  # noqa: E402  (M1's helpers; globals redirected to W1 below)

sys.path.insert(0, HERE)
sys.modules.pop("design", None)
import design as D  # noqa: E402

PROJ = os.path.join(HERE, "..")
OUT = os.path.join(PROJ, D.NAME + ".kicad_pcb")
KFP = os.environ.get("KICAD_FOOTPRINT_DIR", "/usr/share/kicad/footprints")
# JLCPCB 2-layer standard: 0.127 mm track/space, 0.3 mm via drill; here with margin
TRACK, CLEAR, VIA, POWER_TRACK = 0.15, 0.15, (0.6, 0.3), 0.3   # 0.3: still fits a 0.5 mm pitch QFN pin
M.D, M.PROJ, M.OUT = D, PROJ, OUT
M.TRACK, M.CLEAR, M.VIA, M.POWER_TRACK = TRACK, CLEAR, VIA, POWER_TRACK
mm, P = pcbnew.FromMM, M.P
POT_SHAFT = (7.5, 2.5)                  # Alps RK09K vertical: shaft relative to pad 1 (KiCad footprint)


def load_fp(fpid):
    lib, name = fpid.split(":")
    path = os.path.join(D.M1_LIB, "ShtukaDruka.pretty") if lib == "ShtukaDruka" else os.path.join(KFP, lib + ".pretty")
    fp = pcbnew.FootprintLoad(path, name)
    assert fp is not None, fpid
    fp.SetFPID(pcbnew.LIB_ID(lib, name))
    return fp


def rule_area(b, name, x0, y0, x1, y1):
    z = pcbnew.ZONE(b)
    z.SetIsRuleArea(True)
    z.SetLayerSet(pcbnew.LSET.AllCuMask(D.LAYERS))
    z.SetDoNotAllowTracks(True)
    z.SetDoNotAllowVias(True)
    z.SetDoNotAllowCopperPour(False)
    z.SetDoNotAllowPads(False)
    z.SetDoNotAllowFootprints(False)
    z.SetZoneName(name)
    o = z.Outline()
    o.NewOutline()
    for hx, hy in ((x0, y0), (x1, y0), (x1, y1), (x0, y1)):
        q = P(hx, hy)
        o.Append(q.x, q.y)
    b.Add(z)


def rect(b, x0, y0, x1, y1, layer=pcbnew.Edge_Cuts, w=0.1):
    e = pcbnew.PCB_SHAPE(b)
    e.SetShape(pcbnew.SHAPE_T_RECT)
    e.SetStart(P(x0, y0))
    e.SetEnd(P(x1, y1))
    e.SetLayer(layer)
    e.SetWidth(mm(w))
    b.Add(e)


def build():
    b = pcbnew.BOARD()
    b.SetCopperLayerCount(D.LAYERS)
    ds = b.GetDesignSettings()
    ds.m_TrackMinWidth, ds.m_MinClearance, ds.m_ViasMinSize, ds.m_MinThroughDrill = mm(0.127), mm(0.127), mm(0.5), mm(0.3)
    ds.m_CopperEdgeClearance = mm(0.3)
    nc = ds.m_NetSettings.m_DefaultNetClass
    nc.SetTrackWidth(mm(TRACK))
    nc.SetClearance(mm(CLEAR))
    nc.SetViaDiameter(mm(VIA[0]))
    nc.SetViaDrill(mm(VIA[1]))
    tb = b.GetTitleBlock()
    tb.SetTitle(D.TITLE)
    tb.SetRevision(D.REV)
    tb.SetCompany("Shtuka Druka - open hardware, CERN-OHL-S-2.0")
    tb.SetComment(0, "Generated by gen/make_pcb.py from design.py")

    nets = {}

    def net(name):
        if name not in nets:
            ni = pcbnew.NETINFO_ITEM(b, name)
            b.Add(ni)
            nets[name] = ni
        return nets[name]

    pl = D.placement()
    for p in D.parts():
        fp = load_fp(p["fp"])
        b.Add(fp)
        fp.SetReference(p["ref"])
        fp.SetValue(p["value"])
        if p["ref"].startswith("D"):              # 1615 LED: its reference text is below the minimum height
            fp.Reference().SetVisible(False)
        x, y, r, side = pl[p["ref"]]
        if p["ref"].startswith("RV"):            # put the shaft, not pad 1, at (x, y)
            x, y = x - POT_SHAFT[0], y - POT_SHAFT[1]
        fp.SetPosition(P(x, y))
        fp.SetOrientationDegrees(r)
        if side == "bottom":
            fp.Flip(fp.GetPosition(), True)
        if p["ref"].startswith("J"):             # centre the pad field on (x, y)
            xs = [pd.GetPosition().x for pd in fp.Pads()]
            ys = [pd.GetPosition().y for pd in fp.Pads()]
            t = P(x, y)
            fp.Move(pcbnew.VECTOR2I(t.x - (min(xs) + max(xs)) // 2, t.y - (min(ys) + max(ys)) // 2))
        if p["ref"].startswith(("RV", "SW", "D", "H", "J")):
            fp.SetLocked(True)                   # set by the panel and the mechanics
        if p["ref"].startswith("H"):
            for pad in fp.Pads():
                pad.SetLocalClearance(mm(0.35))
        for pad in fp.Pads():
            n = p["pins"].get(pad.GetNumber())
            if n:
                pad.SetNet(net(n))

    # outline with the window for M5
    rect(b, 0, 0, D.W, D.H)
    wx0, wy0, wx1, wy1 = D.window()
    rect(b, wx0, wy0, wx1, wy1)
    e = 0.35                                     # copper-to-edge, for the router
    for x0, y0, x1, y1 in ((0, 0, D.W, e), (0, D.H - e, D.W, D.H), (0, 0, e, D.H), (D.W - e, 0, D.W, D.H),
                           (wx0 - e, wy0 - e, wx1 + e, wy1 + e)):
        rule_area(b, "edge", x0, y0, x1, y1)

    # silkscreen (English on the device, R45)
    for txt, x, y in ((f"W1 Levels rev {D.REV}", 46, 30.0 - 4.5), ("Shtuka Druka  CERN-OHL-S-2.0", 46, 30.0 - 2.5)):
        t = pcbnew.PCB_TEXT(b)
        t.SetText(txt)
        t.SetPosition(P(x, y))
        t.SetLayer(pcbnew.B_SilkS)
        t.SetTextSize(pcbnew.VECTOR2I(mm(0.9), mm(0.9)))
        t.SetTextThickness(mm(0.13))
        t.SetMirrored(True)
        b.Add(t)
    return b


def gnd_pour(b, layer, prio):
    poly = pcbnew.SHAPE_POLY_SET()
    poly.NewOutline()
    for x, y in ((0.3, 0.3), (D.W - 0.3, 0.3), (D.W - 0.3, D.H - 0.3), (0.3, D.H - 0.3)):
        q = P(x, y)
        poly.Append(q.x, q.y)
    hole = pcbnew.SHAPE_POLY_SET()
    hole.NewOutline()
    wx0, wy0, wx1, wy1 = D.window()
    for x, y in ((wx0 - 0.3, wy0 - 0.3), (wx1 + 0.3, wy0 - 0.3), (wx1 + 0.3, wy1 + 0.3), (wx0 - 0.3, wy1 + 0.3)):
        q = P(x, y)
        hole.Append(q.x, q.y)
    poly.BooleanSubtract(hole, pcbnew.SHAPE_POLY_SET.PM_FAST)
    z = pcbnew.ZONE(b)
    z.SetLayer(layer)
    z.SetNet(b.FindNet("GND"))
    z.SetAssignedPriority(prio) if hasattr(z, "SetAssignedPriority") else z.SetPriority(prio)
    z.SetMinThickness(mm(0.25))
    z.SetLocalClearance(mm(0.3))
    z.SetPadConnection(pcbnew.ZONE_CONNECTION_FULL)
    z.SetIslandRemovalMode(pcbnew.ISLAND_REMOVAL_MODE_ALWAYS)
    poly.thisown = False
    z.SetOutline(poly)
    b.Add(z)


def parity_fix(b):
    """Make the board agree with the schematic the way KiCad 10's parity check reads it (CI, 13.11.2026: 127 warnings):
    net names as the schematic netlist writes them (local labels get "/": AIN0 -> /AIN0; single pins
    "unconnected-(...)"), the symbol fields (LCSC, Note) on the footprints, mounting holes in the BOM like their symbols."""
    import re
    import subprocess
    import tempfile
    sch = os.path.join(HERE, "..", D.NAME + ".kicad_sch")
    net = os.path.join(tempfile.mkdtemp(), "w1.net")
    subprocess.run(["kicad-cli", "sch", "export", "netlist", "--format", "kicadsexpr", "-o", net, sch], check=True,
                   capture_output=True)
    pin_net = {}
    for m in re.finditer(r'\(net \(code "?\d+"?\) \(name "([^"]*)"\)(.*?)(?=\n\s*\(net \(code|\Z)', open(net).read(), re.S):
        for ref, pin in re.findall(r'\(node \(ref "?([^")\s]+)"?\) \(pin "?([^")\s]+)"?\)', m.group(2)):
            pin_net[(ref, pin)] = m.group(1)
    rename, single = {}, 0
    for fp in b.GetFootprints():
        for p in fp.Pads():
            want = pin_net.get((fp.GetReference(), p.GetNumber()))
            have = p.GetNetname()
            if want and have and want != have and not have.startswith("unconnected-"):
                rename[have] = want
            elif want and not have and want.startswith("unconnected-"):      # KiCad names single pins' nets too
                n = pcbnew.NETINFO_ITEM(b, want)
                b.Add(n)
                p.SetNet(n)
                single += 1
    for old, new in rename.items():
        n = b.FindNet(old)
        if n:
            n.SetNetname(new)
    fields = {p["ref"]: p["fields"] for p in D.parts()}
    nf = 0
    for fp in b.GetFootprints():
        ref = fp.GetReference()
        for k, v in fields.get(ref, {}).items():                      # LCSC, Note, ... as on the symbol
            fp.SetProperty(k, v)
            nf += 1
        if ref.startswith("H"):                                       # the hole symbols are in the BOM (in_bom yes)
            fp.SetAttributes(fp.GetAttributes() & ~pcbnew.FP_EXCLUDE_FROM_BOM)
    return len(rename), single, nf


if __name__ == "__main__":
    board = build()
    if "--route" in sys.argv:
        jar = sys.argv[sys.argv.index("--route") + 1]
        passes = int(sys.argv[sys.argv.index("--passes") + 1]) if "--passes" in sys.argv else 30
        ses = M.route(board, jar, passes)
        board = build()
        print("imported", M.import_ses(board, ses), "tracks and vias")
    if "--ses" in sys.argv:
        print("imported", M.import_ses(board, sys.argv[sys.argv.index("--ses") + 1]), "tracks and vias")
    board.Save(OUT)
    M.write_project()
    board = pcbnew.LoadBoard(OUT)
    if ("--route" in sys.argv or "--ses" in sys.argv) and "--no-pour" not in sys.argv:
        gnd_pour(board, pcbnew.B_Cu, 1)
        gnd_pour(board, pcbnew.F_Cu, 0)
        M.fill(board)
        print("stitching vias", M.stitch(board, pitch=4.0, margin=0.7))
        M.fill(board)
    print("parity fix: nets renamed %d, single-pin nets %d, fields %d" % parity_fix(board))
    board.Save(OUT)
    M.write_project()
    print("ok", OUT, len(board.GetFootprints()), "footprints", len(board.GetTracks()), "tracks/vias")
