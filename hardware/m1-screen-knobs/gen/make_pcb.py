#!/usr/bin/env python3
"""Build the M1 board from design.py with KiCad's pcbnew Python module (KiCad 7 or newer),
optionally autoroute it with Freerouting.

  python3 make_pcb.py                      # placement + nets + GND plane, unrouted
  python3 make_pcb.py --route FREEROUTING.jar [--passes 60]

Stack-up: 4 layers. F.Cu - LED pads and encoder pins; In1.Cu - GND plane, cut out under the
encoders (they are touch electrodes); In2.Cu, B.Cu - signals; all ICs on B (bottom).
License: AGPL-3.0-or-later (code), CERN-OHL-S-2.0 (the generated board).
"""
import os
import re
import subprocess
import time
import sys

import pcbnew

import json

import design as D

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.join(HERE, "..")
OUT = os.path.join(PROJ, D.NAME + ".kicad_pcb")
KFP = os.environ.get("KICAD_FOOTPRINT_DIR", "/usr/share/kicad/footprints")
ORG = (40.0, 40.0)                      # where the board sits on the drawing sheet, mm
POWER_NETS = ("+5V", "GND")
SW_TRACK = 0.25                         # LED anode rows (SW): up to ~0.35 A per cell; 0.25 mm still enters the 0.4 mm QFN pads
# JLCPCB 4-layer capability: 0.09 mm track/space, 0.2 mm via drill, 0.254 mm via hole to track. The LED driver is QFN-60 with 0.4 mm pitch.
TRACK, CLEAR, VIA, POWER_TRACK = 0.12, 0.13, (0.45, 0.2), 0.3   # 0.13 + ring 0.125 = 0.255 via hole to track
mm = pcbnew.FromMM


def P(x, y):
    return pcbnew.VECTOR2I(mm(ORG[0] + x), mm(ORG[1] + y))


def load_fp(fpid):
    lib, name = fpid.split(":")
    path = os.path.join(PROJ, "lib", "ShtukaDruka.pretty") if lib == "ShtukaDruka" else os.path.join(KFP, lib + ".pretty")
    fp = pcbnew.FootprintLoad(path, name)
    assert fp is not None, fpid
    fp.SetFPID(pcbnew.LIB_ID(lib, name))
    return fp


def save(b, path):
    """Board.Save. Not-fitted parts are marked like in the schematic: excluded from BOM and position files
    (the KiCad 8+ "dnp" flag cannot be written by KiCad 7's API, and KiCad 7/Quilter reject it in a KiCad 7 file)."""
    b.Save(path)


def build():
    b = pcbnew.BOARD()
    b.SetCopperLayerCount(D.LAYERS)
    b.SetLayerType(pcbnew.In1_Cu, pcbnew.LT_POWER)
    ds = b.GetDesignSettings()
    ds.m_TrackMinWidth, ds.m_MinClearance, ds.m_ViasMinSize, ds.m_MinThroughDrill = mm(0.1), mm(0.1), mm(0.4), mm(0.2)
    ds.m_CopperEdgeClearance = mm(0.3)
    nc = ds.m_NetSettings.m_DefaultNetClass
    nc.SetTrackWidth(mm(TRACK))
    nc.SetClearance(mm(CLEAR))
    nc.SetViaDiameter(mm(VIA[0]))
    nc.SetViaDrill(mm(VIA[1]))
    tb = b.GetTitleBlock()
    tb.SetTitle(D.TITLE)
    tb.SetRevision(D.REV)
    tb.SetCompany("Shtuka Druka - open hardware, CERN-OHL-S-2.0")
    tb.SetComment(0, "Generated by gen/make_pcb.py from design.py")

    nets = {}

    def net(name):
        if name not in ("+5V", "+3V3", "GND"):
            name = "/" + name                      # schematic local label (parity with KiCad's net names)
        if name not in nets:
            ni = pcbnew.NETINFO_ITEM(b, name)
            b.Add(ni)
            nets[name] = ni
        return nets[name]

    pl = D.placement()
    for p in D.parts():
        fp = load_fp(p["fp"])
        b.Add(fp)                                # flipping needs the board
        fp.SetReference(p["ref"])
        fp.SetValue(p["value"])
        if p["ref"].startswith("D"):              # 104 LED references would not fit; they are in the fab drawing
            fp.Reference().SetVisible(False)
        x, y, r, side = pl[p["ref"]]
        fp.SetPosition(P(x, y))
        if p["ref"].startswith("ENC"):          # footprint origin is pin A; put the shaft at (x, y)
            mps = [pd.GetPosition() for pd in fp.Pads() if pd.GetNumber() == "MP"]
            cx, cy = sum(v.x for v in mps) // 2, sum(v.y for v in mps) // 2
            fp.SetPosition(pcbnew.VECTOR2I(2 * P(x, y).x - cx, 2 * P(x, y).y - cy))
        fp.SetOrientationDegrees(r)
        if side == "bottom":
            fp.Flip(fp.GetPosition(), True)
        if p["ref"] == "J1":                     # centre the pad field on (x, y)
            xs = [pd.GetPosition().x for pd in fp.Pads()]
            ys = [pd.GetPosition().y for pd in fp.Pads()]
            t = P(x, y)
            fp.Move(pcbnew.VECTOR2I(t.x - (min(xs) + max(xs)) // 2, t.y - (min(ys) + max(ys)) // 2))
        if p["ref"][0] in "DH" or p["ref"].startswith(("ENC", "J")):
            fp.SetLocked(True)                   # set by the panel: knobs, ring LEDs, bus connector, holes
        if p["ref"].startswith("H"):             # mounting holes: keep copper 0.35 mm away (JLCPCB: NPTH to copper 0.254)
            for pad in fp.Pads():
                pad.SetLocalClearance(mm(0.35))
        if p["fields"].get("DNP") == "yes":
            fp.SetAttributes(fp.GetAttributes() | pcbnew.FP_EXCLUDE_FROM_BOM | pcbnew.FP_EXCLUDE_FROM_POS_FILES)
        for k, v in p["fields"].items():          # symbol fields on the footprint too (schematic parity)
            if k not in ("DNP", "Side"):
                fp.SetProperty(k, v)
        for pad in fp.Pads():
            n = p["pins"].get(pad.GetNumber())
            if n:
                pad.SetNet(net(n))

    # outline
    e = pcbnew.PCB_SHAPE(b)
    e.SetShape(pcbnew.SHAPE_T_RECT)
    e.SetStart(P(0, 0))
    e.SetEnd(P(D.W, D.H))
    e.SetLayer(pcbnew.Edge_Cuts)
    e.SetWidth(mm(0.1))
    b.Add(e)

    # no tracks or vias under the encoder bodies: the frame is a touch electrode
    for k in range(8):
        x, y = D.knob_xy(k)
        z = pcbnew.ZONE(b)
        z.SetIsRuleArea(True)
        z.SetLayerSet(pcbnew.LSET.AllCuMask(D.LAYERS))
        z.SetDoNotAllowTracks(True)
        z.SetDoNotAllowVias(True)
        z.SetDoNotAllowCopperPour(True)
        z.SetDoNotAllowPads(False)
        z.SetDoNotAllowFootprints(False)
        z.SetZoneName(f"under_encoder_{k + 1}")
        o = z.Outline()
        o.NewOutline()
        for hx, hy in ((x - 6.2, y - 4.4), (x + 6.2, y - 4.4), (x + 6.2, y + 4.4), (x - 6.2, y + 4.4)):
            q = P(hx, hy)
            o.Append(q.x, q.y)
        b.Add(z)
    # a 0.35 mm strip along the edges: the router does not know the copper-to-edge rule
    e = 0.35
    for x0, y0, x1, y1 in ((0, 0, D.W, e), (0, D.H - e, D.W, D.H), (0, 0, e, D.H), (D.W - e, 0, D.W, D.H)):
        z = pcbnew.ZONE(b)
        z.SetIsRuleArea(True)
        z.SetLayerSet(pcbnew.LSET.AllCuMask(D.LAYERS))
        z.SetDoNotAllowTracks(True)
        z.SetDoNotAllowVias(True)
        z.SetDoNotAllowCopperPour(False)
        z.SetDoNotAllowPads(False)
        z.SetDoNotAllowFootprints(False)
        z.SetZoneName("edge")
        o = z.Outline()
        o.NewOutline()
        for hx, hy in ((x0, y0), (x1, y0), (x1, y1), (x0, y1)):
            q = P(hx, hy)
            o.Append(q.x, q.y)
        b.Add(z)
    gnd_zone(b, pcbnew.In1_Cu, 0)               # the plane: the router connects GND to it with vias
    hug(b)
    side_normals(b)
    driver_fanout(b)
    ring_arcs(b)

    # silkscreen notes
    for txt, x in ((f"M1 rev {D.REV}  CERN-OHL-S-2.0", D.GAP[7] - 1.6),
                   ("Shtuka Druka M1  Param 1-8", D.GAP[7] + 1.6)):     # gap 7 is free on the bottom
        t = pcbnew.PCB_TEXT(b)
        t.SetText(txt)
        t.SetPosition(P(x, D.H / 2))
        t.SetLayer(pcbnew.B_SilkS)
        t.SetTextSize(pcbnew.VECTOR2I(mm(0.8), mm(0.8)))
        t.SetTextThickness(mm(0.12))
        t.SetTextAngleDegrees(90)
        t.SetMirrored(True)
        b.Add(t)
    return b


def hug(b):
    """Decoupling capacitors right at their pins (D.HUG): the capacitor lies parallel to the IC edge,
    just outside the pad row, its pin 1 (supply) in line with the IC pin; rows 1, 2 sit further out."""
    for cap, ic, pin, row in D.HUG:
        u = b.FindFootprintByReference(ic)
        c = b.FindFootprintByReference(cap)
        pad = [p for p in u.Pads() if p.GetNumber() == pin][0]
        uc, pp = u.GetPosition(), pad.GetPosition()
        dx, dy = pp.x - uc.x, pp.y - uc.y
        along_x = abs(dy) >= abs(dx)              # pin on a top/bottom edge: capacitor lies along x
        c.SetOrientationDegrees(0 if along_x else 90)
        pb = pad.GetBoundingBox()
        cb = c.GetBoundingBox(False, False) if hasattr(c, "GetBoundingBox") else None
        half = (cb.GetHeight() if along_x else cb.GetWidth()) / 2
        gap = mm(0.25)
        off = sum(mm(1.0) for _ in range(row))     # each row ~1 mm further out
        if along_x:
            edge = pb.GetBottom() if dy > 0 else pb.GetTop()
            y = edge + (1 if dy > 0 else -1) * (gap + half + off)
            c.SetPosition(pcbnew.VECTOR2I(pp.x, int(y)))
        else:
            edge = pb.GetRight() if dx > 0 else pb.GetLeft()
            x = edge + (1 if dx > 0 else -1) * (gap + half + off)
            c.SetPosition(pcbnew.VECTOR2I(int(x), pp.y))
        p1 = [q for q in c.Pads() if q.GetNumber() == "1"][0].GetPosition()   # supply pad in line with the pin
        shift = pcbnew.VECTOR2I(pp.x - p1.x, 0) if along_x else pcbnew.VECTOR2I(0, pp.y - p1.y)
        c.Move(shift)


FAN_ROT = 225          # deg after the flip: side 2 (SW, CS1-5) faces front-right, side 3 (CS6-18) front-left
FAN_PITCH, FAN_B, FAN_D0, FAN_D1 = 0.86, 4.45, 4.95, 5.70   # mm: via pitch along a side; bend, via rows 0 and 1 (distance from the centre)


def driver_fanout(b):
    """Rev 0.3: fan-out of the LED drivers (QFN-60, 0.4 mm pitch) drawn here and locked, as the rings are.
    Quilter (job F) and Freerouting both left 17 CS lines stuck at the pad columns. Every signal pad gets a
    0.12 mm stub straight out of the pad, a short bend (to FAN_B) onto its lane, then straight to its via; even pads
    of a side end in row 0, odd pads in row 1, whose lanes run midway between the row-0 vias (pitch 0.86: 0.43 to a
    via centre, 0.406 needed for 0.13 clearance).
    Supply pins (+5V, GND) and unused pins stay free for the decoupling capacitors."""
    import math
    for u in D.DRIVER.values():
        fp = b.FindFootprintByReference(u)
        fp.SetOrientationDegrees(FAN_ROT)
        fp.SetLocked(True)
        c = fp.GetPosition()
        for pad in fp.Pads():
            num = pad.GetNumber()
            if not num.isdigit() or int(num) > 60 or pad.GetNetname() in ("", "+5V", "GND"):
                continue
            n = int(num) - 1
            side, i = n // 15, n % 15                      # 0..3, position along the side
            # local frame of the footprint (before rotation, after the flip x is mirrored by pcbnew itself):
            # use the real pad position to find the outward normal
            px, py = pcbnew.ToMM(pad.GetPosition().x - c.x), pcbnew.ToMM(pad.GetPosition().y - c.y)
            sx, sy = (side_vec := SIDE_NORMALS[fp.GetReference()][side])
            tx, ty = -sy, sx                               # along the side
            t_pad = px * tx + py * ty
            if i % 2 == 0:
                d, t = FAN_D0, (i // 2 - 3.5) * FAN_PITCH
            else:
                d, t = FAN_D1, ((i - 1) // 2 - 3) * FAN_PITCH
            # pad index runs the same way as t? choose the sign that keeps t close to the pad
            if abs(t - t_pad) > abs(-t - t_pad):
                t = -t
            out = 3.95
            e1 = (sx * out + tx * t_pad, sy * out + ty * t_pad)
            e2 = (sx * FAN_B + tx * t, sy * FAN_B + ty * t)
            v = (sx * d + tx * t, sy * d + ty * t)
            def V(q):
                return pcbnew.VECTOR2I(c.x + mm(q[0]), c.y + mm(q[1]))
            for s0, s1 in ((pad.GetPosition(), V(e1)), (V(e1), V(e2)), (V(e2), V(v))):
                tr = pcbnew.PCB_TRACK(b)
                tr.SetStart(s0); tr.SetEnd(s1); tr.SetWidth(mm(TRACK)); tr.SetLayer(pcbnew.B_Cu)
                tr.SetNet(pad.GetNet()); tr.SetLocked(True); b.Add(tr)
            via = pcbnew.PCB_VIA(b)
            via.SetPosition(V(v)); via.SetWidth(mm(VIA[0])); via.SetDrill(mm(VIA[1]))
            via.SetNet(pad.GetNet()); via.SetLocked(True); b.Add(via)


SIDE_NORMALS = {}


def side_normals(b):
    """Outward unit normal of each pad side (1-15, 16-30, 31-45, 46-60) of every driver, from the pad positions."""
    for u in D.DRIVER.values():
        fp = b.FindFootprintByReference(u)
        fp.SetOrientationDegrees(FAN_ROT)
        c = fp.GetPosition()
        res = []
        for side in range(4):
            ps = [p.GetPosition() for p in fp.Pads() if p.GetNumber().isdigit() and side * 15 < int(p.GetNumber()) <= side * 15 + 15]
            x = sum(pcbnew.ToMM(p.x - c.x) for p in ps) / len(ps)
            y = sum(pcbnew.ToMM(p.y - c.y) for p in ps) / len(ps)
            r = (x * x + y * y) ** 0.5
            res.append((x / r, y / r))
        SIDE_NORMALS[u] = res


RING_G, RING_B, VIA_SIDE = 13.10, 10.90, 1.30   # mm: outer G arc, inner B arc, via offset beside a pad


def ring_arcs(b):
    """Cathode arcs of every LED ring, drawn here instead of by a router (doc 33; tried on ring 1 with DRC):
    G on F.Cu outside the ring, B on F.Cu inside, R through a via beside its pad to an arc on In2.Cu;
    the anode (SW) gets one via beside its pad and goes down to the SW rows. 2 vias per LED. Locked."""
    import math
    W = mm(TRACK)

    def add(t, layer, net):
        t.SetWidth(W)
        t.SetLayer(layer)
        t.SetNet(net)
        t.SetLocked(True)
        b.Add(t)

    for k in range(8):
        kx, ky = D.knob_xy(k)
        C = P(kx, ky)
        to_mm = pcbnew.ToMM

        def polar(v):
            x, y = to_mm(v.x - C.x), to_mm(v.y - C.y)
            return math.hypot(x, y), math.atan2(y, x)

        def pt(r, a):
            return pcbnew.VECTOR2I(C.x + mm(r * math.cos(a)), C.y + mm(r * math.sin(a)))

        info = []
        for i in range(D.RING_N):
            fp = b.FindFootprintByReference(f"D{k * D.RING_N + i + 1}")
            ac = polar(fp.GetPosition())[1]
            d = {}
            for pad in fp.Pads():
                r, a = polar(pad.GetPosition())
                d[pad.GetNumber()] = dict(r=r, a=a, pos=pad.GetPosition(), net=pad.GetNet())
            for num, q in d.items():
                if num == "3":
                    t = pcbnew.PCB_TRACK(b); t.SetStart(q["pos"]); t.SetEnd(pt(RING_G, q["a"])); add(t, pcbnew.F_Cu, q["net"])
                elif num == "4":
                    t = pcbnew.PCB_TRACK(b); t.SetStart(q["pos"]); t.SetEnd(pt(RING_B, q["a"])); add(t, pcbnew.F_Cu, q["net"])
                else:                              # "1" R, "2" anode: via beside the pad, away from the LED centre
                    side = math.copysign(1, (q["a"] - ac + math.pi) % (2 * math.pi) - math.pi)
                    q["va"] = q["a"] + side * VIA_SIDE / q["r"]
                    vp = pt(q["r"], q["va"])
                    t = pcbnew.PCB_TRACK(b); t.SetStart(q["pos"]); t.SetEnd(vp); add(t, pcbnew.F_Cu, q["net"])
                    v = pcbnew.PCB_VIA(b); v.SetPosition(vp); v.SetWidth(mm(VIA[0])); v.SetDrill(mm(VIA[1]))
                    v.SetNet(q["net"]); v.SetLocked(True); b.Add(v)
            info.append(d)
        for d1, d2 in zip(info, info[1:]):
            for num, layer in (("3", pcbnew.F_Cu), ("4", pcbnew.F_Cu), ("1", pcbnew.In2_Cu)):
                if d1[num]["net"].GetNetCode() != d2[num]["net"].GetNetCode():
                    continue
                if num == "1":
                    r, a1, a2 = (d1["1"]["r"] + d2["1"]["r"]) / 2, d1["1"]["va"], d2["1"]["va"]
                else:
                    r, a1, a2 = (RING_G if num == "3" else RING_B), d1[num]["a"], d2[num]["a"]
                dd = (a2 - a1 + math.pi) % (2 * math.pi) - math.pi
                t = pcbnew.PCB_ARC(b)
                t.SetStart(pt(r, a1)); t.SetMid(pt(r, a1 + dd / 2)); t.SetEnd(pt(r, a1 + dd))
                add(t, layer, d1[num]["net"])


def gnd_zone(b, layer, prio):
    """GND copper on a layer, cut out under every encoder: the encoder frame is a touch electrode."""
    poly = pcbnew.SHAPE_POLY_SET()
    poly.NewOutline()
    for x, y in ((0.3, 0.3), (D.W - 0.3, 0.3), (D.W - 0.3, D.H - 0.3), (0.3, D.H - 0.3)):
        p = P(x, y)
        poly.Append(p.x, p.y)
    for k in range(8):
        x, y = D.knob_xy(k)
        hole = pcbnew.SHAPE_POLY_SET()
        hole.NewOutline()
        for hx, hy in ((x - 6.0, y - 8.0), (x + 6.0, y - 8.0), (x + 6.0, y + 8.0), (x - 6.0, y + 8.0)):   # frame +-6; GND pins C, S2 stay on the plane
            p = P(hx, hy)
            hole.Append(p.x, p.y)
        poly.BooleanSubtract(hole, pcbnew.SHAPE_POLY_SET.PM_FAST)
    z = pcbnew.ZONE(b)
    z.SetLayer(layer)
    z.SetNet(b.FindNet("GND"))
    z.SetAssignedPriority(prio) if hasattr(z, "SetAssignedPriority") else z.SetPriority(prio)
    z.SetMinThickness(mm(0.2))
    z.SetLocalClearance(mm(0.3))
    z.SetPadConnection(pcbnew.ZONE_CONNECTION_FULL)       # GND pins and thermal vias: solid
    z.SetIslandRemovalMode(pcbnew.ISLAND_REMOVAL_MODE_ALWAYS)   # no floating copper
    poly.thisown = False                         # the zone takes ownership of the outline
    z.SetOutline(poly)
    b.Add(z)
    return z


def _sexpr(txt):
    """Minimal s-expression reader: nested lists of strings (linear, no regex backtracking)."""
    stack, cur = [], []
    for t in re.findall(r'\(|\)|"[^"]*"|[^\s()]+', txt):
        if t == "(":
            stack.append(cur)
            cur = []
        elif t == ")":
            done, cur = cur, stack.pop()
            cur.append(done)
        else:
            cur.append(t.strip('"'))
    return cur[0]


def _kids(node, key):
    return [c for c in node if isinstance(c, list) and c and c[0] == key]


def import_ses(b, path):
    """Add the wires and vias of a Specctra session file (pcbnew's own importer needs the GUI)."""
    routes = _kids(_sexpr(open(path).read()), "routes")[0]
    res = _kids(routes, "resolution")[0]
    unit = {"um": 1e-3, "mm": 1.0, "mil": 0.0254, "inch": 25.4}[res[1]] / int(res[2])
    to = lambda v: pcbnew.FromMM(float(v) * unit)
    layers = {b.GetLayerName(l): l for l in range(pcbnew.PCB_LAYER_ID_COUNT) if pcbnew.IsCopperLayer(l)}
    vdia = {ps[1]: c[2] for lib in _kids(routes, "library_out") for ps in _kids(lib, "padstack")
            for sh in _kids(ps, "shape") for c in _kids(sh, "circle")}
    n = 0
    for no in _kids(routes, "network_out"):
        for nt in _kids(no, "net"):
            net = b.FindNet(nt[1])
            for w in _kids(nt, "wire"):
                for pth in _kids(w, "path"):
                    v = [int(x) for x in pth[3:] if not isinstance(x, list)]
                    xy = [(to(v[i]), -to(v[i + 1])) for i in range(0, len(v) - 1, 2)]
                    for (x0, y0), (x1, y1) in zip(xy, xy[1:]):
                        t = pcbnew.PCB_TRACK(b)
                        t.SetStart(pcbnew.VECTOR2I(x0, y0))
                        t.SetEnd(pcbnew.VECTOR2I(x1, y1))
                        t.SetWidth(to(pth[2]))
                        t.SetLayer(layers[pth[1]])
                        t.SetNet(net)
                        b.Add(t)
                        n += 1
            for v in _kids(nt, "via"):
                via = pcbnew.PCB_VIA(b)
                via.SetPosition(pcbnew.VECTOR2I(to(v[2]), -to(v[3])))
                via.SetWidth(to(vdia.get(v[1], 6000)))
                via.SetDrill(pcbnew.FromMM(VIA[1]))
                via.SetNet(net)
                b.Add(via)
                n += 1
    return n


def copy_tracks(b, path, rip=None):
    """Take tracks and vias from an earlier routed board with the same placement and nets.
    rip = (x0, y0, x1, y1) board mm: leave out everything touching that box, the router redoes it."""
    src = pcbnew.LoadBoard(path)
    n = 0
    lo, hi = P(0.45, 0.45), P(D.W - 0.45, D.H - 0.45)
    for t in src.GetTracks():
        bb = t.GetBoundingBox()
        if bb.GetLeft() < lo.x or bb.GetTop() < lo.y or bb.GetRight() > hi.x or bb.GetBottom() > hi.y:
            continue                             # too close to the edge: let the router redo it
        if rip:
            r0, r1 = P(rip[0], rip[1]), P(rip[2], rip[3])
            if bb.GetRight() > r0.x and bb.GetLeft() < r1.x and bb.GetBottom() > r0.y and bb.GetTop() < r1.y:
                continue
        c = t.Duplicate()
        c.SetParent(b)
        c.SetNet(b.FindNet(t.GetNetname()))
        b.Add(c)
        n += 1
    return n


def write_project():
    """Design rules and net classes live in the project file (KiCad 7 and newer)."""
    cls = dict(clearance=CLEAR, track_width=TRACK, via_diameter=VIA[0], via_drill=VIA[1], microvia_diameter=0.3,
               microvia_drill=0.1, diff_pair_gap=0.25, diff_pair_width=0.2, diff_pair_via_gap=0.25,
               wire_width=6, bus_width=12, line_style=0)
