#!/usr/bin/env python3
"""Write the M3 schematic (KiCad 7 file format; KiCad 7-10 open it) from design.py.

Reuses M1's schematic writer (every pin gets a net label or a power symbol at its end, so the netlist
matches design.py exactly). On a machine with KiCad newer than 7, first build KiCad-7-format symbols:
  python ../../common/gen/sym7.py  and run with KICAD_SYMBOL_DIR=<repo>/hardware/common/sym7
Run: python3 make_sch.py       License: AGPL-3.0-or-later (code), CERN-OHL-S-2.0 (the schematic).
"""
import os
import sys
import uuid

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "common", "gen"))
import m1compat  # noqa: E402  (loads M1's writer also on Python 3.11)

M = m1compat.load("make_sch")             # it imports M1's design as M.D, replaced below
sys.path.insert(0, HERE)
sys.modules.pop("design", None)
import design as D  # noqa: E402

M.D = D
M.PROJ_LIB = os.path.join(D.M1_LIB, "ShtukaDruka.kicad_sym")
M.NS = uuid.UUID("3a9c2f41-7d0e-4b8a-9c61-0e5d2f7b3a03")
M.ROOT = str(uuid.uuid5(M.NS, "root"))
OUT = os.path.join(HERE, "..", D.NAME + ".kicad_sch")


class Sch(M.Sch):
    def write(self, path):
        libs = "".join("  " + M.lib_block(l)[0].replace("\n", "\n  ") + "\n" for l in self.used)
        s = (f'(kicad_sch (version 20230121) (generator eeschema)\n\n  (uuid {M.ROOT})\n\n  (paper "A3")\n\n'
             f'  (title_block\n    (title {M.q(D.TITLE)})\n    (rev {M.q(D.REV)})\n'
             f'    (company "Shtuka Druka - open hardware, CERN-OHL-S-2.0")\n'
             f'    (comment 1 "Generated by hardware/{D.NAME}/gen/make_sch.py from design.py - edit the script, not this file")\n'
             f'    (comment 2 "LP5864 0x40 (ADDR 00): Tempo ring CS9-17, Swing ring CS0-8; chain reads Tempo A B push, Swing A B push, 1, 1")\n  )\n\n'
             f'  (lib_symbols\n{libs}  )\n\n' + "".join(self.items) +
             f'\n  (sheet_instances\n    (path "/" (page "1"))\n  )\n)\n')
        open(path, "w", encoding="utf-8").write(s)


def main():
    P = {p["ref"]: p for p in D.parts()}
    S = Sch()

    def put(ref, x, y, r=0):
        p = P[ref]
        f = {k: v for k, v in p["fields"].items() if k not in ("DNP", "Side")}
        S.symbol(ref, p["lib"], p["value"], x, y, r, p["fp"], f, p["pins"], dnp=p["fields"].get("DNP") == "yes",
                 in_bom=not ref.startswith("H"))           # mounting holes: not in the BOM, as their footprint says

    g = 2.54
    S.text("Module bus (R123): J1 to P1 (I2C channel 1 of P1's TCA9546A); chain: P1 buttons -> M3 -> W1", 10 * g, 8 * g)
    put("J1", 20 * g, 18 * g)
    for net, x in (("+5V", 10), ("+3V3", 14), ("GND", 18)):
        S.power(net, x * g, 34 * g, 90 if net != "GND" else 270, flag=True)
    for i, ref in enumerate(("C1", "C2", "R1", "R2", "R3")):
        put(ref, (26 + 5 * i) * g, 34 * g)
    S.text("Encoders Tempo, Swing (EC11E, frame MP on GND: no touch, P102) -> 74HC165", 10 * g, 44 * g)
    put("ENC1", 16 * g, 54 * g)
    put("ENC2", 30 * g, 54 * g)
    put("RN1", 42 * g, 54 * g)
    put("RN2", 50 * g, 54 * g)
    put("U2", 64 * g, 56 * g)
    put("C7", 76 * g, 64 * g)
    S.text("LED rings: one LP5864 (24 RGB = 4 SW x 18 CS), 12 LEDs per ring", 90 * g, 8 * g)
    put("U1", 104 * g, 30 * g)
    for i, ref in enumerate(("C3", "C4", "C5", "C6")):
        put(ref, (120 + 5 * i) * g, 18 * g)
    for n in range(24):
        put(f"D{n + 1}", (90 + 6 * (n % 12)) * g, (52 + 14 * (n // 12)) * g)
    for h in range(len(D.HOLES)):
        put(f"H{h + 1}", (120 + 5 * h) * g, 30 * g)
    S.write(OUT)
    print("ok", OUT, len(P), "parts")


if __name__ == "__main__":
    main()
