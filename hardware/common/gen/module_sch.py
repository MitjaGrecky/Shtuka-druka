"""Schematic writer for the two-encoder modules built with kit.knob_pair (M4, M5; M3 has its own copy).
Uses M1's writer (m1compat). Every pin gets a label or power symbol at its end.
License: AGPL-3.0-or-later (code), CERN-OHL-S-2.0 (the generated schematic).
"""
import os
import uuid

import m1compat


def _writer(D, ns, comment2, here):
    M = m1compat.load("make_sch")
    M.D = D
    M.PROJ_LIB = os.path.join(D.M1_LIB, "ShtukaDruka.kicad_sym")
    M.NS = uuid.UUID(ns)
    M.ROOT = str(uuid.uuid5(M.NS, "root"))

    class Sch(M.Sch):
        def write(self, path):
            libs = "".join("  " + M.lib_block(l)[0].replace("\n", "\n  ") + "\n" for l in self.used)
            s = (f'(kicad_sch (version 20230121) (generator eeschema)\n\n  (uuid {M.ROOT})\n\n  (paper "A3")\n\n'
                 f'  (title_block\n    (title {M.q(D.TITLE)})\n    (rev {M.q(D.REV)})\n'
                 f'    (company "Shtuka Druka - open hardware, CERN-OHL-S-2.0")\n'
                 f'    (comment 1 "Generated by hardware/{D.NAME}/gen/make_sch.py from design.py - edit the script, not this file")\n'
                 f'    (comment 2 {M.q(comment2)})\n  )\n\n'
                 f'  (lib_symbols\n{libs}  )\n\n' + "".join(self.items) +
                 f'\n  (sheet_instances\n    (path "/" (page "1"))\n  )\n)\n')
            open(path, "w", encoding="utf-8").write(s)
    return M, Sch()


BIG = {"ShtukaDruka:LP5864": (16, 26), "74xx:74HC165": (12, 16), "Connector_Generic:Conn_02x07_Odd_Even": (12, 14),
       "Connector_Generic:Conn_02x08_Odd_Even": (12, 16), "Interface_Expansion:TCA9546APW": (18, 22),
       "Analog_ADC:ADS1115IDGS": (16, 14), "Common:AS5600": (14, 12), "Connector_Generic:Conn_01x02": (8, 8),
       "Sensor_Touch:CY8CMBR3108": (14, 16),
       "ShtukaDruka:RotaryEncoder_Switch_Touch": (12, 12)}   # pins at +-3 grid: a 6-wide cell would join neighbours


def write_grid(D, ns, comment2, here, notes=()):
    """Any board: J1 and the power flags top left, then every part in rows (ICs and connectors in a wider grid).
    The drawing is a parts sheet: every pin carries its net label, so the netlist is exact."""
    M, S = _writer(D, ns, comment2, here)
    g = 2.54
    for i, t in enumerate(notes or (getattr(D, "BUS_NOTE", ""),)):
        S.text(t, 10 * g, (6 + 3 * i) * g)
    for net, x in (("+5V", 10), ("+3V3", 14), ("GND", 18)):
        S.power(net, x * g, 20 * g, 90 if net != "GND" else 270, flag=True)
    P = D.parts()
    x, y, row_h = 26, 20, 0
    big = [p for p in P if p["lib"] in BIG]
    small = [p for p in P if p["lib"] not in BIG]
    for p in big + small:
        w, h = BIG.get(p["lib"], (6, 10))
        if x + w > 150:
            x, y, row_h = 10, y + row_h, 0
        f = {k: v for k, v in p["fields"].items() if k not in ("DNP", "Side")}
        S.symbol(p["ref"], p["lib"], p["value"], (x + w / 2) * g, (y + h / 2) * g, 0, p["fp"], f, p["pins"],
                 dnp=p["fields"].get("DNP") == "yes", in_bom=not p["ref"].startswith("H"))
        x += w
        row_h = max(row_h, h)
    out = os.path.join(here, "..", D.NAME + ".kicad_sch")
    S.write(out)
    print("ok", out, len(P), "parts")


def write(D, ns, comment2, here):
    M = m1compat.load("make_sch")
    M.D = D
    M.PROJ_LIB = os.path.join(D.M1_LIB, "ShtukaDruka.kicad_sym")
    M.NS = uuid.UUID(ns)
    M.ROOT = str(uuid.uuid5(M.NS, "root"))
    out = os.path.join(here, "..", D.NAME + ".kicad_sch")

    class Sch(M.Sch):
        def write(self, path):
            libs = "".join("  " + M.lib_block(l)[0].replace("\n", "\n  ") + "\n" for l in self.used)
            s = (f'(kicad_sch (version 20230121) (generator eeschema)\n\n  (uuid {M.ROOT})\n\n  (paper "A3")\n\n'
                 f'  (title_block\n    (title {M.q(D.TITLE)})\n    (rev {M.q(D.REV)})\n'
                 f'    (company "Shtuka Druka - open hardware, CERN-OHL-S-2.0")\n'
                 f'    (comment 1 "Generated by hardware/{D.NAME}/gen/make_sch.py from design.py - edit the script, not this file")\n'
                 f'    (comment 2 {M.q(comment2)})\n  )\n\n'
                 f'  (lib_symbols\n{libs}  )\n\n' + "".join(self.items) +
                 f'\n  (sheet_instances\n    (path "/" (page "1"))\n  )\n)\n')
            open(path, "w", encoding="utf-8").write(s)

    P = {p["ref"]: p for p in D.parts()}
    S = Sch()

    def put(ref, x, y, r=0):
        p = P[ref]
        f = {k: v for k, v in p["fields"].items() if k not in ("DNP", "Side")}
        S.symbol(ref, p["lib"], p["value"], x, y, r, p["fp"], f, p["pins"], dnp=p["fields"].get("DNP") == "yes",
                 in_bom=not ref.startswith("H"))

    g = 2.54
    S.text(D.BUS_NOTE, 10 * g, 8 * g)
    put("J1", 20 * g, 18 * g)
    for net, x in (("+5V", 10), ("+3V3", 14), ("GND", 18)):
        S.power(net, x * g, 34 * g, 90 if net != "GND" else 270, flag=True)
    for i, ref in enumerate(("C1", "C2", "R1", "R2", "R3")):
        put(ref, (26 + 5 * i) * g, 34 * g)
    S.text(f"Encoders {D.KNOBS[0][0]}, {D.KNOBS[1][0]} (EC11E, frame MP on GND: no touch, P102) -> 74HC165", 10 * g, 44 * g)
    put("ENC1", 16 * g, 54 * g)
    put("ENC2", 30 * g, 54 * g)
    put("RN1", 42 * g, 54 * g)
    put("RN2", 50 * g, 54 * g)
    put("U2", 64 * g, 56 * g)
    put("C7", 76 * g, 64 * g)
    leds = sorted((r for r in P if r.startswith("D")), key=lambda r: int(r[1:]))
    S.text(f"LEDs: one LP5864 (24 RGB = 4 SW x 18 CS), {len(leds)} LEDs", 90 * g, 8 * g)
    put("U1", 104 * g, 30 * g)
    for i, ref in enumerate(("C3", "C4", "C5", "C6")):
        put(ref, (120 + 5 * i) * g, 18 * g)
    for n, ref in enumerate(leds):
        put(ref, (90 + 6 * (n % 12)) * g, (52 + 14 * (n // 12)) * g)
    holes = [r for r in P if r.startswith("H")]
    for h, ref in enumerate(holes):
        put(ref, (120 + 5 * h) * g, 30 * g)
    S.write(out)
    print("ok", out, len(P), "parts")
