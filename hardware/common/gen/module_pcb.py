"""Board writer for the kit-based boards (pcbnew, KiCad 7 or newer): outline, holes, parts placed from
design.placement(), panel parts locked (encoders, LEDs, holes, connectors), nets with the schematic's names,
symbol fields copied hidden, open pins named as KiCad does, edge keep-out. No routing.
License: AGPL-3.0-or-later (code), CERN-OHL-S-2.0 (the generated board).
"""
import os

import pcbnew

import boardkit as B
import kit as K

mm, P = pcbnew.FromMM, B.P
LOCKED = ("ENC", "D", "H", "J", "SW", "RV")


def load_fp(D, fpid):
    lib, name = fpid.split(":")
    kfp = os.environ.get("KICAD_FOOTPRINT_DIR", "/usr/share/kicad/footprints")
    path = os.path.join(D.M1_LIB, "ShtukaDruka.pretty") if lib == "ShtukaDruka" else os.path.join(kfp, lib + ".pretty")
    fp = pcbnew.FootprintLoad(path, name)
    assert fp is not None, fpid
    fp.SetFPID(pcbnew.LIB_ID(lib, name))
    return fp


def rule_area(D, b, name, x0, y0, x1, y1):
    z = pcbnew.ZONE(b)
    z.SetIsRuleArea(True)
    z.SetLayerSet(pcbnew.LSET.AllCuMask(D.LAYERS))
    z.SetDoNotAllowTracks(True)
    z.SetDoNotAllowVias(True)
    for setter in ("SetDoNotAllowCopperPour", "SetDoNotAllowZoneFills"):     # KiCad 7 / KiCad 9+ name
        if hasattr(z, setter):
            getattr(z, setter)(False)
    z.SetDoNotAllowPads(False)
    z.SetDoNotAllowFootprints(False)
    z.SetZoneName(name)
    o = z.Outline()
    o.NewOutline()
    for hx, hy in ((x0, y0), (x1, y0), (x1, y1), (x0, y1)):
        q = P(hx, hy)
        o.Append(q.x, q.y)
    b.Add(z)


def build(D, silk):
    b = pcbnew.BOARD()
    b.SetCopperLayerCount(D.LAYERS)
    ds = b.GetDesignSettings()
    ds.m_TrackMinWidth, ds.m_MinClearance, ds.m_ViasMinSize, ds.m_MinThroughDrill = mm(0.127), mm(0.127), mm(0.5), mm(0.3)
    ds.m_CopperEdgeClearance = mm(0.3)
    tb = b.GetTitleBlock()
    tb.SetTitle(D.TITLE)
    tb.SetRevision(D.REV)
    tb.SetCompany("Shtuka Druka - open hardware, CERN-OHL-S-2.0")
    tb.SetComment(0, "Generated by gen/make_pcb.py from design.py")
    nets = {}

    def net_raw(name):
        if name not in nets:
            ni = pcbnew.NETINFO_ITEM(b, name)
            b.Add(ni)
            nets[name] = ni
        return nets[name]

    def net(name):                                         # local labels of the root sheet carry a "/", as in the schematic
        return net_raw(name if name in B.POWER_NETS else "/" + name)

    pl = D.placement()
    for p in D.parts():
        fp = load_fp(D, p["fp"])
        b.Add(fp)
        fp.SetReference(p["ref"])
        fp.SetValue(p["value"])
        if p["ref"].startswith("D"):
            fp.Reference().SetVisible(False)
        x, y, r, side = pl[p["ref"]]
        if p["ref"].startswith("ENC"):                     # footprint origin is pad A; put the shaft at (x, y)
            x, y = x - K.ENC_SHAFT[0], y - K.ENC_SHAFT[1]
        fp.SetPosition(P(x, y))
        fp.SetOrientationDegrees(r)
        if side == "bottom":
            B.flip_bottom(fp)                              # same result in KiCad 7 and 9/10 (#15)
        if p["ref"].startswith(("J", "RV")):               # centre the pad field on (x, y) (connectors, slide pots)
            xs = [pd.GetPosition().x for pd in fp.Pads()]
            ys = [pd.GetPosition().y for pd in fp.Pads()]
            t = P(x, y)
            fp.Move(pcbnew.VECTOR2I(t.x - (min(xs) + max(xs)) // 2, t.y - (min(ys) + max(ys)) // 2))
        if p["ref"].startswith(LOCKED):
            fp.SetLocked(True)                             # set by the panel and the mechanics
        if p["ref"].startswith("H"):
            for pad in fp.Pads():
                pad.SetLocalClearance(mm(0.35))
        if p["fields"].get("DNP") == "yes" and hasattr(fp, "SetDNP"):
            fp.SetDNP(True)
        B.copy_fields(fp, {k: v for k, v in p["fields"].items() if k not in ("DNP", "Side")})
        for pad in fp.Pads():
            num = pad.GetNumber()
            n = p["pins"].get(num)
            if n:
                pad.SetNet(net(n))
            elif num in p["pins"]:                         # pin left open: KiCad's name for it, so parity is clean
                pad.SetNet(net_raw(f"unconnected-({p['ref']}-{B.pin_name(p['lib'], num)}-Pad{num})"))

    g = 0.35                                               # copper-to-edge keep-out for the router
    outline = getattr(D, "OUTLINE", None)                  # polygon (board mm) for boards with a notch; else the W x H rectangle
    if outline:
        pts = list(outline) + [outline[0]]
        for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
            e = pcbnew.PCB_SHAPE(b)
            e.SetShape(pcbnew.SHAPE_T_SEGMENT)
            e.SetStart(P(x0, y0))
            e.SetEnd(P(x1, y1))
            e.SetLayer(pcbnew.Edge_Cuts)
            e.SetWidth(mm(0.1))
            b.Add(e)
            rule_area(D, b, "edge", min(x0, x1) - g, min(y0, y1) - g, max(x0, x1) + g, max(y0, y1) + g)
    else:
        e = pcbnew.PCB_SHAPE(b)
        e.SetShape(pcbnew.SHAPE_T_RECT)
        e.SetStart(P(0, 0))
        e.SetEnd(P(D.W, D.H))
        e.SetLayer(pcbnew.Edge_Cuts)
        e.SetWidth(mm(0.1))
        b.Add(e)
        for x0, y0, x1, y1 in ((0, 0, D.W, g), (0, D.H - g, D.W, D.H), (0, 0, g, D.H), (D.W - g, 0, D.W, D.H)):
            rule_area(D, b, "edge", x0, y0, x1, y1)
    for txt, (x, y) in silk:                              # English only (R45), bottom silkscreen
        t = pcbnew.PCB_TEXT(b)
        t.SetText(txt)
        t.SetPosition(P(x, y))
        t.SetLayer(pcbnew.B_SilkS)
        t.SetTextSize(pcbnew.VECTOR2I(mm(0.8), mm(0.8)))
        t.SetTextThickness(mm(0.12))
        t.SetMirrored(True)
        b.Add(t)
    return b


def main(D, silk, here):
    proj = os.path.join(here, "..")
    out = os.path.join(proj, D.NAME + ".kicad_pcb")
    board = build(D, silk)
    board.Save(out)
    B.write_project(proj, D.NAME, getattr(D, "LAYERS", 2))
    print("ok", out, len(board.GetFootprints()), "footprints")
